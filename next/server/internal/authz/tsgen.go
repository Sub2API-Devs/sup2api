package authz

import (
	"fmt"
	"strings"
	"unicode"

	"github.com/Sub2API-Devs/sup2api/next/server/internal/perm"
)

// PermissionsTS renders the core permission catalog as the console's
// next/web/src/generated/permissions.ts (`sub2api permissions-ts`;
// TestGeneratedPermissionsTS keeps the checked-in file in step): a constant
// per key, the scopable actions and their former own-level aliases, each key's flags, soft dependencies and
// description, the key types and the role key pattern. The output is
// already in the console's prettier style.
func PermissionsTS() string {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }
	perms := listedPerms()

	w("// Code generated by `sub2api permissions-ts` from the core permission catalog")
	w("// (next/server/internal/authz); DO NOT EDIT. TestGeneratedPermissionsTS fails when")
	w("// it is stale: regenerate with UPDATE_GOLDEN=1 go test ./internal/authz -run TestGeneratedPermissionsTS.")
	w("")
	w("/** Every core permission key, the self module's included, by name. */")
	w("export const P = {")
	for i, p := range perms {
		w("  %s: %s%s", tsName(p.key), tsString(string(p.key)), comma(i, len(perms)))
	}
	w("} as const")
	w("")
	w("export type PermKey = (typeof P)[keyof typeof P]")
	w("")
	w("/** The scopable actions and the resource their scope ranges over (CONTRACTS §21). */")
	w("export const SCOPE_TYPE = {")
	var scopable []listedPerm
	for _, p := range perms {
		if perm.ScopeType(p.key) != "" {
			scopable = append(scopable, p)
		}
	}
	for i, p := range scopable {
		w("  %s: %s%s", tsString(string(p.key)), tsString(string(perm.ScopeType(p.key))), comma(i, len(scopable)))
	}
	w("} as const")
	w("")
	w("export type ScopableKey = keyof typeof SCOPE_TYPE")
	w("")
	w("/** The former own-level key of each scopable action: a deprecated alias of <action>:own, still in /me (CONTRACTS §21). */")
	w("export const LEGACY_OWN = {")
	for i, p := range scopable {
		w("  %s: %s%s", tsString(string(p.key)), tsString(perm.LegacyOwnKey(p.key)), comma(i, len(scopable)))
	}
	w("} as const")
	w("")
	w("export type LegacyOwnKey = (typeof LEGACY_OWN)[ScopableKey]")
	w("/** A scopable action with a scope: account:read:own, account:update:group/12, … */")
	w("export type ScopedPermKey = `${ScopableKey}:${string}`")
	w("/** A plugin permission: plugin.<plugin key>:<local key>. */")
	w("export type PluginPermKey = `plugin.${string}:${string}`")
	w("/** Any permission key the console names in code. */")
	w("export type PermRef = PermKey | ScopedPermKey | LegacyOwnKey | PluginPermKey")
	w("")
	w("export interface PermMeta {")
	w("  module: string")
	w("  /** Flagged in the role editor: credentials, money, trust roots, code execution, identity. */")
	w("  sensitive: boolean")
	w("  /** Some of its routes need a step-up proof each time (CONTRACTS §80.2). */")
	w("  stepUp: boolean")
	w("  /** Soft dependencies, of the same scope for a scopable action; editor hints only. */")
	w("  requires: readonly PermKey[]")
	w("  description: { en: string; zh: string }")
	w("}")
	w("")
	w("export const PERMISSIONS: Record<PermKey, PermMeta> = {")
	for i, p := range perms {
		w("  %s: {", tsString(string(p.key)))
		w("    module: %s,", tsString(p.module))
		w("    sensitive: %t,", p.sensitive)
		w("    stepUp: %t,", p.stepUp)
		req := make([]string, len(p.requires))
		for j, k := range p.requires {
			req[j] = tsString(string(k))
		}
		w("    requires: [%s],", strings.Join(req, ", "))
		w("    description: {")
		w("      en: %s,", tsString(p.desc.Get("en")))
		w("      zh: %s", tsString(p.desc.Get("zh")))
		w("    }")
		w("  }%s", comma(i, len(perms)))
	}
	w("}")
	w("")
	w("/** A custom role's key (authz roleKeyRe). */")
	w("export const ROLE_KEY_PATTERN = /%s/", roleKeyRe.String())
	return b.String()
}

// listedPerm is a catalog permission with its module.
type listedPerm struct {
	corePerm
	module string
}

// listedPerms are the core and self permissions in catalog order, the
// former own-level aliases left out.
func listedPerms() []listedPerm {
	var out []listedPerm
	for _, m := range append(coreModules[:len(coreModules):len(coreModules)], selfModule) {
		for _, p := range m.perms {
			if !p.deprecated {
				out = append(out, listedPerm{p, m.key})
			}
		}
	}
	return out
}

// tsName is a key's constant name: "user:password:reset" → UserPasswordReset.
func tsName(k perm.Key) string {
	var b strings.Builder
	for _, part := range strings.FieldsFunc(string(k), func(r rune) bool { return r == ':' || r == '_' }) {
		r := []rune(part)
		r[0] = unicode.ToUpper(r[0])
		b.WriteString(string(r))
	}
	return b.String()
}

// tsString quotes s as prettier would: single quotes unless s holds one and
// no double quote.
func tsString(s string) string {
	q := "'"
	if strings.Contains(s, "'") && !strings.Contains(s, `"`) {
		q = `"`
	}
	r := strings.NewReplacer(`\`, `\\`, q, `\`+q, "\n", `\n`)
	return q + r.Replace(s) + q
}

func comma(i, n int) string {
	if i < n-1 {
		return ","
	}
	return ""
}
