/**
 * 按扩展名判断是否为二进制文件。
 */
function hasBinaryExtension(filePath) {
  let ext = filePath.slice(filePath.lastIndexOf(".")).toLowerCase();
  return BINARY_EXTENSIONS.has(ext);
}
