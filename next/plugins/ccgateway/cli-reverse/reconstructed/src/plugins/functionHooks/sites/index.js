var MAX_SURFACES = 64;
//@ chunk-j8f885h1.js:8335-9066 placement
/**
 * 按界面（surface + requestId）记录各客户端占用的行数，判断是否放得下，行数减少时发出 freed 信号（最多保留 64 个界面）。
 */
function createSurfaceRowLedger() {
  let ledger = new Map();
  let signal = createSignal();
  function rowFor(owner) {
    let existing = ledger.get(surfaceBudgetKey(owner));
    let row = existing ?? {
      own: 0,
      clients: new Map(),
    };
    if (existing === undefined) {
      ledger.set(surfaceBudgetKey(owner), row);
      for (let key of ledger.keys()) {
        if (ledger.size <= MAX_SURFACES) break;
        ledger.delete(key);
      }
    }
    return row;
  }
  function emitIfShrank(owner, before, after) {
    if (after < before) signal.emit(owner);
  }
  return {
    clientRows: (owner) => ledger.get(surfaceBudgetKey(owner))?.clients.get(paneOwnerLabel(owner)) ?? 1,
    clientsOf: (owner) => [...(ledger.get(surfaceBudgetKey(owner))?.clients ?? [])],
    holdClients: (owner, clients) => {
      rowFor(owner).clients = new Map(clients);
    },
    recordOwn: (owner, amount) => {
      let row = rowFor(owner);
      let own = row.own;
      row.own = amount;
      emitIfShrank(owner, own, amount);
    },
    fits: (owner, own, limit) => {
      let row = rowFor(owner);
      let label = paneOwnerLabel(owner);
      let total = row.own + own;
      for (let [clientLabel, clientCost] of row.clients) total += clientLabel === label ? 0 : clientCost;
      return total <= limit;
    },
    recordClient: (owner, amount) => {
      let { clients } = rowFor(owner);
      let label = paneOwnerLabel(owner);
      let before = clients.get(label) ?? 0;
      clients.set(label, amount);
      emitIfShrank(owner, before, amount);
    },
    dropClient: (owner) => {
      if (ledger.get(surfaceBudgetKey(owner))?.clients.delete(paneOwnerLabel(owner)) === true)
        signal.emit(owner);
    },
    onFreed: signal.subscribe,
    clear: () => {
      ledger.clear();
    },
  };
}
