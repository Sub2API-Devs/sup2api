function pixelRowsToPath(frame) {
  let pathData = "";
  frame.forEach((row, rowIndex) => {
    for (let run of row.matchAll(/#+/g))
      pathData += `M${run.index} ${rowIndex}h${run[0].length}v1h-${run[0].length}z`;
  });
  return pathData;
}
