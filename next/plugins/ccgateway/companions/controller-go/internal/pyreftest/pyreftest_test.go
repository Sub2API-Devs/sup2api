package pyreftest

import (
	"os"
	"testing"
)

// covers: 05-§6 (the reference vector files exist and are well formed)
func TestVectorFiles(t *testing.T) {
	for _, name := range []string{"json_dumps.json", "fingerprint.json", "container_identity.json", "outbound_tag.json",
		"network_policy.json", "python_semantics.json", "texts.json", "state_samples.json"} {
		cases := Cases(t, name)
		if Str(cases[0], "name") == "" && name != "python_semantics.json" {
			t.Errorf("%s: unnamed case", name)
		}
	}
	if _, err := os.Stat(Dir()); err != nil {
		t.Fatal(err)
	}
	var doc struct {
		Generator string `json:"generator"`
		Python    string `json:"python"`
	}
	Load(t, "fingerprint.json", &doc)
	if doc.Generator == "" || doc.Python[:4] != "3.12" {
		t.Fatalf("generated by %q with Python %q", doc.Generator, doc.Python)
	}
}
