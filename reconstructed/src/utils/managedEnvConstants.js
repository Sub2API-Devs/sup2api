/**
 * 环境变量是否为“关闭”值（falsy 或 none）且未在其他来源中定义。
 */
function isDisablingTelemetryEnv(envName, value, getEffectiveEnv) {
  if (
    envName !== envName.toUpperCase() ||
    (typeof value !== "string" && typeof value !== "number" && typeof value !== "boolean")
  )
    return false;
  if (
    !(OTEL_PROMPT_LOG_VARS.has(envName)
      ? isEnvDefinedFalsy(typeof value === "boolean" ? value : String(value))
      : OTEL_EXPORTER_MODE_VARS.has(envName) && String(value).trim() === "none")
  )
    return false;
  return !Object.keys(getEffectiveEnv()).some((key) => key.toUpperCase() === envName);
}
