/**
 * 取文本前 N 个词（去掉粘贴/图片占位符）生成小写短横线 slug。
 */
function slugifyPromptWords(e, s = {}) {
  let { words = 4, maxLen = 40 } = s;
  return e
    .replace(PASTED_PLACEHOLDER_PATTERN, " ")
    .split(/\s+/)
    .filter(Boolean)
    .slice(0, words)
    .join(" ")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .slice(0, maxLen)
    .replace(/^-+|-+$/g, "");
}
