function pixelRowsToPath(frame) {
  let t = "";
  frame.forEach((r, n) => {
    for (let i of r.matchAll(/#+/g)) t += `M${i.index} ${n}h${i[0].length}v1h-${i[0].length}z`;
  });
  return t;
}
