var Wp = 64;
/**
 * 按界面（surface + requestId）记录各客户端占用的行数，判断是否放得下，行数减少时发出 freed 信号（最多保留 64 个界面）。
 */
//@ chunk-4121qate.js:8226-8957 placement
function createSurfaceRowLedger() {
  let e = new Map(),
    o = createSignal();
  function r(s) {
    let i = e.get(qRt(s)),
      p = i ?? { own: 0, clients: new Map() };
    if (i === void 0) {
      e.set(qRt(s), p);
      for (let f of e.keys()) {
        if (e.size <= Wp) break;
        e.delete(f);
      }
    }
    return p;
  }
  function n(s, i, p) {
    if (p < i) o.emit(s);
  }
  return {
    clientRows: (s) => e.get(qRt(s))?.clients.get(go(s)) ?? 1,
    clientsOf: (s) => [...(e.get(qRt(s))?.clients ?? [])],
    holdClients: (s, i) => {
      r(s).clients = new Map(i);
    },
    recordOwn: (s, i) => {
      let p = r(s),
        own = p.own;
      ((p.own = i), n(s, own, i));
    },
    fits: (s, i, p) => {
      let f = r(s),
        a = go(s),
        m = f.own + i;
      for (let [c, u] of f.clients) m += c === a ? 0 : u;
      return m <= p;
    },
    recordClient: (s, i) => {
      let { clients: clients } = r(s),
        f = go(s),
        a = clients.get(f) ?? 0;
      (clients.set(f, i), n(s, a, i));
    },
    dropClient: (s) => {
      if (e.get(qRt(s))?.clients.delete(go(s)) === !0) o.emit(s);
    },
    onFreed: o.subscribe,
    clear: () => {
      e.clear();
    },
  };
}

